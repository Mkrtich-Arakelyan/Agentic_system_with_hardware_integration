"""No provider calls: injected model mocks and unchanged tiny image attachments."""

import base64
from copy import deepcopy
from dataclasses import replace
import json
from pathlib import Path
import unittest
from unittest.mock import Mock

from langchain_core.exceptions import OutputParserException
from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import AIMessage
from PIL import Image
from pydantic import ValidationError

from app.agents.scientist import ScientistResponse as scientific_response_model, scientist as scientist_turn
from app.agents.photo_quality_specialist import (
    CandidateMeasurement, ImageAttachment, ImageLabel, MissingImage,
    PHOTO_QUALITY_PROMPT, PhotoQualitySpecialistError, SpecialistEvidence,
    SpecialistInputError, photo_quality_specialist, prepare_specialist_messages,
)
from app.print_tuning.validation import get_candidate_correspondence
from tests.print_tuning import test_validation as fixtures


class SpecialistTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        # Reuse real trial/1 manifests generated by the existing validator fixtures.
        fixtures.ValidationTests.setUpClass()
        cls.addClassCleanup(fixtures.ValidationTests.doClassCleanups)

    def setUp(self):
        self.fixture = fixtures.ValidationTests()
        self.path = Path(fixtures.ValidationTests.temp.name) / "tiny.png"
        image = Image.new("RGB", (3, 2))
        image.putdata([(10, 20, 30), (60, 80, 90), (100, 110, 120), (130, 140, 150), (180, 190, 200), (220, 230, 240)])
        image.save(self.path)

    def inputs(self, stage="propose_gamma"):
        context = self.fixture.context(stage)
        record = context.reviewed_manifest or self.fixture.manifests[1]
        items = {item["item_id"]: item for item in record["items"]}
        limits = {e: deepcopy(items[self.fixture.association[e]]["limits"]) for e in fixtures.IDS}
        if stage == "propose_gamma":
            images = [ImageAttachment(ImageLabel("source_preview", e, panel), self.path)
                      for e in fixtures.IDS for panel in ("Initial", "Final")]
            evidence = SpecialistEvidence(limits, images)
        else:
            identities = get_candidate_correspondence(context)
            images = [ImageAttachment(ImageLabel("scanned_candidate", c.experiment_id, panel,
                                                 c.candidate_id, c.variation_id), self.path)
                      for c in identities for panel in ("Initial", "Final")]
            first = identities[0]
            evidence = SpecialistEvidence(
                limits, images, trial_id=record["trial_id"], round_id=record["round_id"],
                candidate_measurements=[CandidateMeasurement(first.experiment_id, first.candidate_id,
                                                             first.variation_id, {"contrast": .12345, "printed_levels": 4},
                                                             panel="Initial", warnings=["Low local contrast"])],
                page_measurements=[{"page_number": 1, "fit_error_mm": .2, "page_code_read": True}],
                printer_response={"combined": {"paper": .72, "black": .12, "gray_patches": []}},
            )
        return context, evidence

    def response(self, stage):
        return fixtures.MODELS[stage](**fixtures.payload(stage))

    def result(self, response):
        return {"parsed": response, "parsing_error": None, "raw": AIMessage(content=response.model_dump_json())}

    def model(self, *results):
        model = Mock(spec=BaseChatModel)
        model.profile = {"image_inputs": True}
        model.with_structured_output.return_value.invoke.side_effect = results
        model.bind_tools.side_effect = AssertionError("Specialist must never bind tools")
        return model

    def test_all_stages_use_correct_schema_and_validated_response(self):
        for stage, schema in fixtures.MODELS.items():
            with self.subTest(stage=stage):
                context, evidence = self.inputs(stage)
                response = self.response(stage)
                model = self.model(self.result(response))
                self.assertIs(photo_quality_specialist(model, context, evidence), response)
                model.with_structured_output.assert_called_once_with(schema, method="json_schema", include_raw=True)
                model.bind_tools.assert_not_called()

    def test_actual_pixels_config_measurements_and_labels_are_in_messages(self):
        context, evidence = self.inputs("review_gamma")
        messages = prepare_specialist_messages(context, evidence)
        self.assertEqual(messages[0].content, PHOTO_QUALITY_PROMPT)
        content = messages[1].content
        metadata = json.loads(content[0]["text"])
        self.assertEqual(metadata["config"], context.config)
        self.assertEqual(metadata["candidate_measurements"][0]["values"]["contrast"], .12345)
        self.assertEqual(metadata["printer_response"]["combined"]["paper"], .72)
        self.assertEqual(metadata["normalization_limits"], evidence.normalization_limits)
        self.assertEqual(metadata["candidate_correspondence"][0]["variation_id"], "ref")
        self.assertEqual(metadata["candidate_correspondence"][1]["candidate_id"], "test_1")
        images = [part for part in content if part["type"] == "image_url"]
        self.assertEqual(len(images), len(evidence.images))
        for part in images:
            prefix, encoded = part["image_url"]["url"].split(",", 1)
            self.assertEqual(prefix, "data:image/png;base64")
            self.assertEqual(base64.b64decode(encoded), self.path.read_bytes())
        self.assertNotIn(str(self.path), json.dumps(content))
        labels = [json.loads(part["text"].removeprefix("Image label: "))
                  for part in content if part["type"] == "text" and part["text"].startswith("Image label: ")]
        self.assertEqual(len(labels), len(images))
        label = labels[0]
        self.assertEqual(label["candidate_id"], "reference")
        self.assertEqual(label["variation_id"], "ref")

    def test_contextual_error_gets_one_correction_with_original_evidence(self):
        context, evidence = self.inputs()
        bad = self.response("propose_gamma")
        bad.experiments[0].tests[0].gamma = 9
        good = self.response("propose_gamma")
        model = self.model(self.result(bad), self.result(good))
        self.assertIs(photo_quality_specialist(model, context, evidence), good)
        calls = model.with_structured_output.return_value.invoke.call_args_list
        first, second = calls[0].args[0], calls[1].args[0]
        self.assertEqual(second[:2], first)
        self.assertIn("outside", second[2].content)
        self.assertIn('"gamma":9', second[2].content)
        self.assertEqual(len(calls), 2)

    def test_two_invalid_decisions_raise_specialist_error(self):
        context, evidence = self.inputs()
        bad = self.response("propose_gamma")
        bad.experiments.pop()
        model = self.model(self.result(bad), self.result(bad))
        with self.assertRaises(PhotoQualitySpecialistError) as caught:
            photo_quality_specialist(model, context, evidence)
        self.assertEqual(len(caught.exception.diagnostics), 2)
        self.assertIn("missing", str(caught.exception))
        self.assertEqual(model.with_structured_output.return_value.invoke.call_count, 2)

    def test_schema_parsing_errors_can_be_corrected(self):
        context, evidence = self.inputs()
        with self.assertRaises(ValidationError) as caught:
            fixtures.MODELS["propose_gamma"](stage="propose_gamma", experiments="wrong")
        for error in (caught.exception, OutputParserException("invalid JSON", llm_output="{bad")):
            model = self.model({"parsed": None, "parsing_error": error, "raw": AIMessage(content="{bad")},
                               self.result(self.response("propose_gamma")))
            photo_quality_specialist(model, context, evidence)
            correction = model.with_structured_output.return_value.invoke.call_args_list[1].args[0][-1].content
            self.assertIn("{bad", correction)
            self.assertEqual(model.with_structured_output.return_value.invoke.call_count, 2)
        model = self.model(OutputParserException("invalid JSON", llm_output="{direct"), self.result(self.response("propose_gamma")))
        photo_quality_specialist(model, context, evidence)
        self.assertIn("{direct", model.with_structured_output.return_value.invoke.call_args_list[1].args[0][-1].content)

    def test_input_files_and_context_errors_do_not_invoke_model(self):
        context, evidence = self.inputs()
        corrupt = self.path.with_name("bad.png")
        corrupt.write_bytes(b"not an image")
        cases = [(replace(context, config={}), evidence),
                 (replace(context, reference_mappings=None), evidence),
                 (context, replace(evidence, images=evidence.images[:-1])),
                 (context, replace(evidence, images=[replace(a, path=self.path.with_name("missing.png")) for a in evidence.images])),
                 (context, replace(evidence, images=[replace(a, path=corrupt) for a in evidence.images]))]
        for index, (ctx, data) in enumerate(cases):
            with self.subTest(case=index):
                model = self.model()
                with self.assertRaises(SpecialistInputError):
                    photo_quality_specialist(model, ctx, data)
                model.with_structured_output.assert_not_called()

    def test_review_identity_attachment_and_measurement_mismatches(self):
        context, evidence = self.inputs("review_gamma")
        wrong = replace(evidence.images[0], label=replace(evidence.images[0].label, variation_id="v0"))
        measurements = [replace(evidence.candidate_measurements[0], variation_id="wrong")]
        limits = deepcopy(evidence.normalization_limits)
        limits[fixtures.IDS[0]]["hi"] += 1
        for data in (replace(evidence, trial_id="other"), replace(evidence, round_id=2),
                     replace(evidence, images=[wrong, *evidence.images[1:]]),
                     replace(evidence, candidate_measurements=measurements),
                     replace(evidence, normalization_limits=limits)):
            model = self.model()
            with self.assertRaises(SpecialistInputError):
                photo_quality_specialist(model, context, data)
            model.with_structured_output.assert_not_called()

    def test_rescan_and_insufficient_contrast_pass_through(self):
        for stage in list(fixtures.MODELS)[1:]:
            for assessment in ("needs_rescan", "insufficient_contrast"):
                context, evidence = self.inputs(stage)
                data = fixtures.payload(stage)
                data.update(assessment=assessment, issues=["Unreliable scan" if assessment == "needs_rescan" else "Measured contrast inadequate"])
                for field in ("gamma_winners", "gamma_tests"):
                    if field in data:
                        data[field] = []
                response = fixtures.MODELS[stage](**data)
                model = self.model(self.result(response))
                if assessment == "needs_rescan":
                    evidence = replace(evidence, images=[], incomplete_evidence_reason="No readable page images available")
                self.assertIs(photo_quality_specialist(model, context, evidence), response)

    def test_partial_images_require_explicit_missing_evidence(self):
        context, evidence = self.inputs("review_gamma_final")
        with self.assertRaises(SpecialistInputError):
            prepare_specialist_messages(context, replace(evidence, images=evidence.images[:-1]))
        missing = MissingImage(evidence.images[-1].label, "Crop was unavailable")
        messages = prepare_specialist_messages(context, replace(evidence, images=evidence.images[:-1], missing_images=[missing]))
        self.assertIn("Crop was unavailable", messages[1].content[0]["text"])

    def test_scan_definitions_and_provenance_are_validated_before_model_calls(self):
        context, evidence = self.inputs("review_gamma")
        source = {"path": "scan.png", "sha256": "a" * 64}
        for data in (replace(evidence, measurement_docs={"contrast": {"units": "gray"}}),
                     replace(evidence, measurement_docs={"contrast": {"units": "", "meaning": "contrast"}}),
                     replace(evidence, scan_files=[{"path": "scan.png", "sha256": "wrong"}]),
                     replace(evidence, scan_files=[source, source]),
                     replace(evidence, scan_quality={"usable": True, "issues": "not a list"})):
            model = self.model()
            with self.assertRaises(SpecialistInputError):
                photo_quality_specialist(model, context, data)
            model.with_structured_output.assert_not_called()

    def test_complete_scan_pages_are_supported(self):
        context, evidence = self.inputs("review_gamma")
        pages = [ImageAttachment(ImageLabel("scan_page", page_number=p["page_number"]), self.path)
                 for p in context.reviewed_manifest["pages"]]
        messages = prepare_specialist_messages(context, replace(evidence, images=pages))
        self.assertEqual(sum(p["type"] == "image_url" for p in messages[1].content), len(pages))

    def test_reference_winners_and_no_final_proposals(self):
        context, evidence = self.inputs("review_gamma_final")
        response = self.response("review_gamma_final")
        model = self.model(self.result(response))
        returned = photo_quality_specialist(model, context, evidence)
        self.assertTrue(all(w.candidate_id == "reference" for w in returned.gamma_winners))
        self.assertNotIn("gamma_tests", returned.model_dump())
        self.assertIn("No further proposals", model.with_structured_output.return_value.invoke.call_args.args[0][1].content[0]["text"])

    def test_proposals_use_resolved_winners_not_prior_settings(self):
        context, evidence = self.inputs("review_gamma")
        response = self.response("review_gamma")
        response.gamma_winners[0].candidate_id = "test_2"
        response.gamma_tests[0].tests[1].gamma = 0.7        # 0.6 is now the winner's gamma
        evidence = replace(evidence, prior_settings={e: dict(self.fixture.base) for e in fixtures.IDS})
        model = self.model(self.result(response))
        self.assertIs(photo_quality_specialist(model, context, evidence), response)
        stale = replace(context, reference_mappings={e: dict(self.fixture.base) for e in fixtures.IDS})
        model = self.model(self.result(response))
        with self.assertRaisesRegex(SpecialistInputError, "stale"):
            photo_quality_specialist(model, stale, evidence)
        self.assertEqual(model.with_structured_output.return_value.invoke.call_count, 1)

    def test_model_capability_and_operational_errors_are_not_corrections(self):
        context, evidence = self.inputs()
        model = self.model()
        model.profile = {"image_inputs": False}
        with self.assertRaisesRegex(SpecialistInputError, "image input"):
            photo_quality_specialist(model, context, evidence)
        model.with_structured_output.assert_not_called()
        model = self.model()
        model.profile = {"image_inputs": True, "structured_output": False}
        with self.assertRaisesRegex(SpecialistInputError, "structured output"):
            photo_quality_specialist(model, context, evidence)
        model.with_structured_output.assert_not_called()
        with self.assertRaises(ValidationError) as request_error:
            AIMessage(content=None)
        for error in (PermissionError("authentication failed"), ValueError("API does not support images"), RuntimeError("network unavailable"), request_error.exception):
            model = self.model(error)
            with self.assertRaises(type(error)):
                photo_quality_specialist(model, context, evidence)
            self.assertEqual(model.with_structured_output.return_value.invoke.call_count, 1)
        model = self.model()
        model.with_structured_output.side_effect = NotImplementedError("json_schema unavailable")
        with self.assertRaises(NotImplementedError):
            photo_quality_specialist(model, context, evidence)

    def test_wrong_manifest_and_candidate_page_fail_before_model_call(self):
        context, evidence = self.inputs("review_gamma")
        wrong_page = replace(evidence.images[0], label=replace(evidence.images[0].label, page_number=2))
        for ctx, data in ((replace(context, expected_trial_id="wrong"), evidence),
                          (context, replace(evidence, images=[wrong_page, *evidence.images[1:]]))):
            model = self.model()
            with self.assertRaises(SpecialistInputError):
                photo_quality_specialist(model, ctx, data)
            model.with_structured_output.assert_not_called()

    def test_wrong_response_stage_and_final_extra_fields_get_correction(self):
        context, evidence = self.inputs("review_gamma_final")
        model = self.model(self.result(self.response("review_gamma")), self.result(self.response("review_gamma_final")))
        self.assertEqual(photo_quality_specialist(model, context, evidence).stage, "review_gamma_final")
        with self.assertRaises(ValidationError) as caught:
            fixtures.MODELS["review_gamma_final"](**(fixtures.payload("review_gamma_final") | {"gamma_tests": []}))
        model = self.model({"parsed": None, "parsing_error": caught.exception, "raw": AIMessage(content='{"gamma_tests": []}')},
                           self.result(self.response("review_gamma_final")))
        photo_quality_specialist(model, context, evidence)
        self.assertEqual(model.with_structured_output.return_value.invoke.call_count, 2)

    def test_no_image_payloads_in_diagnostics_or_correction_text(self):
        context, evidence = self.inputs()
        model = self.model(*[{"parsed": None, "parsing_error": OutputParserException("bad"),
                            "raw": AIMessage(content=[{"type": "text", "text": "data:image/png;base64,SECRETDATA"}])}] * 2)
        with self.assertRaises(PhotoQualitySpecialistError) as caught:
            photo_quality_specialist(model, context, evidence)
        self.assertNotIn("SECRETDATA", str(caught.exception))
        correction = model.with_structured_output.return_value.invoke.call_args_list[1].args[0][-1].content
        self.assertNotIn("SECRETDATA", correction)
        self.assertIn("[image payload omitted]", correction)

    def test_no_files_or_context_are_mutated_and_scientist_exports_unchanged(self):
        context, evidence = self.inputs("review_gamma")
        before = deepcopy(context)
        files = {p: p.read_bytes() for p in self.path.parent.rglob("*") if p.is_file()}
        model = self.model(self.result(self.response("review_gamma")))
        photo_quality_specialist(model, context, evidence)
        self.assertEqual(before, context)
        after = {p: p.read_bytes() for p in self.path.parent.rglob("*") if p.is_file()}
        self.assertEqual(files, after)
        self.assertFalse(any(p.name == "tuning_session.json" for p in after))
        from app.agents import ScientistResponse, scientist
        self.assertIs(ScientistResponse, scientific_response_model)
        self.assertIs(scientist, scientist_turn)


